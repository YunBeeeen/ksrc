@dataclass
class NoiseCfg:
    """구동·센싱 불확실성.  **이쪽이 진짜 흔들어야 할 것이다.**

    형태와 달리 이것들은 실기체에서 매 순간 변하고, 측정해도 없앨 수 없다.
    관측에 노이즈가 없으면 고유수용감각 이력이 너무 깨끗해서 정책이 특권정보
    없이도 풀어버린다 -- teacher-student 가 성립하려면 이게 있어야 한다.
    """
    # 배터리 전압.  기준은 **모터 데이터시트의 12V** 다 (mot_tau_stall/w_noload
    # 가 12V 값).  3S 리포는 그 12V 를 가운데 두고 위아래로 움직인다:
    #     만충 12.6V = 1.05   공칭 11.1V = 0.925   컷오프 9.9V = 0.825
    # 즉 **만충이 모터 정격보다 위**다.  예전 범위 (0.80,1.00) 은 12V 를 천장으로
    # 둬서 만충 구간을 한 번도 안 봤다.
    #
    # 지배적인 변동은 전압 "강하"가 아니라 주행 내내 진행되는 **방전**이다.
    # 120C x 0.65Ah = 78A 감당 팩이라 내부저항이 낮다 (3셀 20~35mOhm).
    # 구동 4개 ~9A 에서 IR 강하는 0.3V = 2.5% 뿐이다. 예전 0.12 는 5배 과장.
    # DC 모터는 tau_stall 과 w_noload 가 **둘 다 전압에 비례**한다.
    volt_scale:   tuple = (0.83, 1.05)   # 12V 스펙 대비 (컷오프 ~ 만충)
    volt_sag_k:   float = 0.03           # 부하 비례 IR 강하

    # 엔코더: 16 PPR x 감속비 -> 8384 tick/rev. 50Hz 에서 양자화가 지배적.
    enc_quant:    float = 1.0            # tick 단위 양자화 (1 = 실제 분해능)
    enc_noise:    float = 0.02           # 상대 백색잡음

    # IMU (ISM330DHCX) 데이터시트 수준 + 바이어스는 에피소드마다 고정
    gyro_noise:   float = 0.010          # rad/s
    gyro_bias:    tuple = (-0.02, 0.02)  # rad/s, 에피소드 상수
    acc_noise:    float = 0.10           # m/s^2
    acc_bias:     tuple = (-0.15, 0.15)  # m/s^2
    rp_noise:     float = 0.004          # roll/pitch [rad] (융합 후)

    # 조향 서보 (STS3215): 지연과 데드밴드
    servo_lag:    tuple = (0.02, 0.06)   # 1차 지연 시정수 [s]
    servo_dead:   float = 0.012          # rad (~0.7도)

    # 제어 지연: Pi -> STM32 -> 서보/모터 왕복.  50Hz 스텝 단위.
    act_delay:    tuple = (0, 2)         # 스텝 (0~40ms)

    # 측위 오차.  관측의 lookahead 웨이포인트는 실기에서 map->odom TF 로
    # 얻으므로 측위 정확도가 그대로 실린다.  시뮬에서 완벽한 웨이포인트를 주면
    # 정책이 실기에 없는 신호를 믿도록 학습된다.
    #
    # 근거: 엔코더+IMU 데드레커닝은 16초/1.7m 주행에서 **845mm** 틀린다
    # (측정값, 완벽한 센서 가정.  원인은 슬립 -- 오차 ~= 평균슬립 x 이동거리).
    # 따라서 절대 측위(D435 + 대회장 맵 ICP)가 전제이고, 그쪽 기대 정확도가
    # 20~50mm 다 (지형 법선의 수평 구속력 lambda_min 최악 1분위 3.3e-3 ->
    # 잡음 한정으로는 1mm 급이지만, 맵 불일치/외부캘리브/깊이 계통오차가 지배).
    # ICP 사이의 짧은 구간은 오도메트리가 메우므로 느린 드리프트도 함께 준다.
    # 잡음은 **저역통과** 해서 준다.  50Hz 로 매 스텝 백색잡음을 주면 조향이
    # 지터를 따라 떨어 scrub 이 0.012 -> 0.21 로 17배 폭발한다.  실제 측위는
    # robot_localization EKF 가 오도메트리(연속)와 ICP(5~15Hz)를 융합해 매끄러운
    # 출력을 내므로, 관측 잡음의 대역이 제어 대역보다 훨씬 낮다.
    # wp_noise 는 **출력 표준편차**이고 wp_tau 가 그 상관시간이다.
    wp_noise:     float = 0.030          # m, 저역통과 후 표준편차
    wp_tau:       float = 0.20           # s, 잡음 상관시간 (EKF 평활)
    wp_drift:     float = 0.040          # m/s, 랜덤워크 (ICP 사이 오도메트리)
    wp_drift_max: float = 0.120          # m, 드리프트 상한 (ICP 가 되잡는 한계)
    wp_yaw_noise: float = 0.020          # rad, 요 추정오차


def sample(cfg: RoverCfg, rng) -> RoverCfg:
    """RANDOM_RANGES 에 따라 파라미터를 흔든 새 cfg 를 만든다.

    주의: uniform 으로 **덮어쓴다**.  그래서 범위는 반드시 실측 공칭값을 품어야
    한다.  wheel_r 이 범위 밖이었던 사고가 여기서 났다.  지금은 형태를 전혀
    흔들지 않으므로 그 위험이 없다.
    """
    return replace(cfg, **{k: float(rng.uniform(*v)) for k, v in RANDOM_RANGES.items()})
