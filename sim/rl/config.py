    #     35도 -> 성공 59%, 만료 34%      31도 -> 53%, 42%
    #     28도 -> 82%, 13%                25도 -> 76%, 21%
    #     21도 -> 80%, 16%  전복 2%   <- 채택 (측정된 한계와 일치, 전복 최소)
    # 주행가능 면적은 75.6% -> 70.4% 로 5%p 만 줄어든다.
    # 3D 차체 잔차의 상한.  행동 a in [-1,1]^3 에 곱한다.
    #
    # 왜 바퀴별 8D 가 아니라 차체 3D 인가:
    #   - 8D 는 바퀴 4개에 독립 각도를 줄 수 있어 **공통 ICR 조건이 깨진다.**
