    #     스워브가 횡이탈을 고치는 방법이 게걸음인데 4D 에는 그게 없다
    #   - 3D 는 IK 가 항상 일관된 해를 만들고 Delta_vy 가 횡보정의 올바른 손잡이다
    #   - 그리고 **펌웨어 변경이 필요 없다** (`V vx vy omega` 그대로).
    #     8D 는 `R vx vy omega dth1..4 dd1..4` 같은 새 명령이 필요했다
    # 범위 축소 (Stage 1 1차 실패 후).  +-0.06/+-0.06/+-0.30 은 **권한이 과했다**:
    #     a 평균 0.854,  a p95 = 1.000  -> 잔차가 상시 포화
    #     cmd 포화 4.8% -> 51.2%        -> 절반의 시간을 실현 한계에서 보냄
    #     슬립 0.153 -> 0.433 (2.8배)   -> IK 가 desaturation 을 반복
    # 특히 Delta_omega +-0.30 은 명령 요속도 중앙(0.105 rad/s)의 3배라 잔차가
    # "보정" 이 아니라 "지배" 였다.  명령과 같은 규모로 줄인다.
    d_vx_max:     float = 0.03           # m/s  (v_cruise 0.22 의 14%)
    d_vy_max:     float = 0.03           # m/s
    d_om_max:     float = 0.10           # rad/s (명령 요속도 중앙과 같은 규모)

    # 바퀴별 모래 차이 (terrain.soil_field).  amp 는 mu 의 상대 표준편차이고
    # 난이도에 비례한다.  이게 0 이면 4바퀴가 같은 흙을 밟아 **좌우 비대칭 슬립이
    # 발생하지 않는다** -- 이 RL 의 목적 현상이 아예 없어진다.
    soil_amp:     float = 0.25           # d=1 에서 mu 가 +-25%
    soil_lam:     float = 0.20           # 상관길이 [m] (트랙폭 0.2367 보다 작게)

    max_slope_deg: float = 21.0

    # pure pursuit 튜닝.  lookahead L = clip(pp_k_v * v_cruise, pp_l_min, pp_l_max).
    # 예전 (2.0, 0.25, 0.80) 은 0.22 m/s 로 가는 로버에 2초짜리 선행이라 횡이탈의
    # 87% 가 이 지연에서 나왔다 (흙 난이도로 슬립을 58% 올려도 e_y 중앙은 5% 만
    # 변했다 -> 슬립이 아니라 컨트롤러 지연).  측위 잡음 하에서 재스윕해 정한다.
    # 측위 잡음(저역통과 30mm + 드리프트) 하에서 30 에피소드 스윕 결과.
    #   k_v  L            e_y중앙  성공  전복  scrub  yaw
    #   2.0  [0.25,0.80]   56.1mm   67%   3%  0.065  0.412   <- 예전값
    #   1.2  [0.18,0.45]   32.9mm   70%   0%  0.060  0.530   <- 채택
    #   0.6  [0.10,0.25]   30.2mm   63%   3%  0.126  0.254
    # 더 짧게 가면 e_y 는 측위 잡음 바닥(~30mm)에 걸려 안 줄고 scrub 만 2배가 된다.
    pp_k_v:       float = 1.2
    pp_l_min:     float = 0.18
    pp_l_max:     float = 0.45

    steer_lim:    float = 3.14159        # +-180deg

    # ---- 인쇄물 부피 [cm^3], STL 실측 (전부 watertight 확인됨) ------------
    @property
    def _printed(self):
        PETG = 1.27e-3                      # kg/cm^3
        k = PETG * self.infill
        return dict(base=459.5*k, arm=78.9*k, wheel=98.4*k,
                    wheel_hub=(44.9+9.5)*k, arm_hub=14.1*k,
                    coupler=7.5*k, bevel_s=9.8*k, bevel_l=32.4*k)

    @property
    def m_base(self) -> float:
        p = self._printed
        return p["base"] + p["bevel_l"] + 2*p["bevel_s"] + self.m_elec + self.m_misc

    @property
    def m_rocker(self) -> float:
        p = self._printed
        return p["arm"] + p["arm_hub"] + p["coupler"]

    @property
    def m_steer(self) -> float:
        return self.m_servo + self._printed["wheel_hub"]

    @property
    def m_wheel(self) -> float:
        return self._printed["wheel"]

    @property
    def wheel_damping(self) -> float:
        """DC 모터 속도 droop == 점성감쇠. b = tau_stall / w_noload."""
        return self.mot_tau_stall / self.mot_w_noload

    @property
    def total_mass(self) -> float:
        return self.m_base + 2*self.m_rocker + 4*(self.m_steer + self.m_wheel + self.m_motor)


