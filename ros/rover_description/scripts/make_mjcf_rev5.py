"""rover_rev5_isaac_cyl.urdf -> mjcf/rover_rev5.xml (2026-10-15).

sim/rl/mjcf.py 가 읽는 CAD MJCF(rover.xml) 와 같은 골격으로 만든다: floating_base freejoint, imu_site,
로커 1:1 역방향 equality, accelerometer/gyro/framequat 센서, 빈 actuator (mjcf.build 가 채움).
바퀴 충돌은 원기둥 (10-15 결정, 볼록껍질 14각형 대신), 몸체는 볼록 껍질.
메쉬 경로는 meshes/ 기준 (rev5/...).  다시 만들 때: python3 scripts/make_mjcf_rev5.py
"""
import os
import re
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

import mujoco

PKG = Path(__file__).resolve().parents[1]
SRC = PKG / "rover_rev5_isaac_cyl.urdf"
OUT = PKG / "mjcf" / "rover_rev5.xml"

txt = SRC.read_text()
comp = (f'<mujoco><compiler meshdir="{PKG}" strippath="false" discardvisual="false" '
        'fusestatic="false" balanceinertia="true"/></mujoco>')
txt = re.sub(r"(<robot[^>]*>)", r"\1" + comp, txt, count=1)
with tempfile.NamedTemporaryFile("w", suffix=".urdf", dir=PKG, delete=False) as f:
    f.write(txt)
    tmp_urdf = f.name
try:
    m = mujoco.MjModel.from_xml_path(tmp_urdf)
finally:
    os.unlink(tmp_urdf)
tmp_xml = Path(tempfile.mkstemp(suffix=".xml")[1])
mujoco.mj_saveLastXML(str(tmp_xml), m)
root = ET.parse(tmp_xml).getroot()
tmp_xml.unlink()

root.set("model", "rover_rev5")
comp = root.find("compiler")
comp.set("meshdir", "../meshes")
comp.set("angle", "radian")
for k in ("strippath", "discardvisual", "fusestatic", "balanceinertia"):
    comp.attrib.pop(k, None)
for mesh in root.find("asset").findall("mesh"):
    mesh.set("file", mesh.get("file").replace("meshes/", "", 1))
if root.find("option") is None:
    root.insert(1, ET.Element("option"))
root.find("option").attrib.update({"timestep": "0.002", "gravity": "0 0 -9.81", "integrator": "implicitfast"})
if root.find("default") is None:
    root.insert(2, ET.Element("default"))

wb = root.find("worldbody")
base = wb.find("body")
assert base.get("name") == "base_link", base.get("name")
base.set("pos", "0 0 0.2")
for j in list(base.findall("joint")) + list(base.findall("freejoint")):
    base.remove(j)
fj = ET.Element("freejoint", {"name": "floating_base"})
base.insert(1 if base.find("inertial") is not None else 0, fj)
# 시각 geom 은 충돌 안 함 (mjcf.build 가 visual=False 일 때 contype=0 메쉬를 지운다)
for b in root.iter("body"):
    for g in b.findall("geom"):
        if g.get("type") == "mesh" and g.get("group") in ("1", "2"):
            g.set("contype", "0"); g.set("conaffinity", "0")
imu = next(b for b in root.iter("body") if b.get("name") == "imu_link")
ET.SubElement(imu, "site", {"name": "imu_site", "pos": "0 0 0", "size": ".001", "rgba": "1 0 0 1"})
wb.insert(0, ET.Element("geom", {"name": "ground", "type": "plane", "size": "5 5 0.1"}))

eq = root.find("equality") or ET.SubElement(root, "equality")
for ch in list(eq):
    eq.remove(ch)
ET.SubElement(eq, "joint", {"joint1": "right_rocker_joint", "joint2": "left_rocker_joint", "polycoef": "0 -1 0 0 0"})
act = root.find("actuator") or ET.SubElement(root, "actuator")
for ch in list(act):
    act.remove(ch)
sen = root.find("sensor") or ET.SubElement(root, "sensor")
for ch in list(sen):
    sen.remove(ch)
ET.SubElement(sen, "accelerometer", {"name": "imu_accelerometer", "site": "imu_site"})
ET.SubElement(sen, "gyro", {"name": "imu_gyro", "site": "imu_site"})
ET.SubElement(sen, "framequat", {"name": "base_orientation", "objtype": "body", "objname": "base_link"})
ET.indent(root)
OUT.write_text("<!-- generated by scripts/make_mjcf_rev5.py from rover_rev5_isaac_cyl.urdf (2026-10-15) -->\n"
               + ET.tostring(root, encoding="unicode"))
mm = mujoco.MjModel.from_xml_path(str(OUT))
print(f"wrote {OUT}: bodies {mm.nbody}, joints {mm.njnt}, mass {mm.body_subtreemass[1]:.4f} kg, "
      f"geoms {mm.ngeom} (cylinders {int((mm.geom_type == mujoco.mjtGeom.mjGEOM_CYLINDER).sum())})")
